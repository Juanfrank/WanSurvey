/** Catalogues to register with the host app's i18next instance under the `renderer` namespace. */
export const rendererResources = { en: { [RENDERER_NS]: en }, es: { [RENDERER_NS]: es } } as const;

/** Text for a validation message: built-in checks are translated, questionnaire rules are already localised. */
export function messageText(t: TFunction, m: ValidationMessage): string {
  if (!m.builtIn) return m.message;
  return t(`validation.${m.ruleId}`, {
    ns: RENDERER_NS,
    defaultValue: m.message,
    ...(m.params ?? {}),
    // Plural forms (decimal places, characters) follow the number in the rule.
    ...(typeof m.params?.n === 'number' ? { count: m.params.n } : {}),
  });
}
