CREATE FUNCTION user_tenants(p_user_id uuid, p_include_inactive boolean DEFAULT false)
  RETURNS TABLE (id uuid, slug text, name text, member_status text)
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
  AS $$
    SELECT t.id, t.slug, t.name, tm.status
    FROM tenant_members tm JOIN tenants t ON t.id = tm.tenant_id
    WHERE tm.user_id = p_user_id AND (p_include_inactive OR tm.status = 'active')
    ORDER BY t.name
  $$;
